import { readFileSync, writeFileSync } from 'node:fs';
const publications = JSON.parse(readFileSync(new URL('../data/publications.json', import.meta.url), 'utf8'));
const escape = text => text.replace(/[\\&%$#_{}~^]/g, char => ({'\\':'\\textbackslash{}','&':'\\&','%':'\\%','$':'\\$','#':'\\#','_':'\\_','{':'\\{','}':'\\}','~':'\\textasciitilde{}','^':'\\textasciicircum{}'}[char]));
let tex = '% Generated by npm run cv:sync from data/publications.json.\n\\begin{rSection}{Publications}\n';
for (const [category, label] of [['peer-reviewed', 'Peer-reviewed Publications'], ['abstract-workshop', 'Abstracts, Workshops and Demos'], ['domestic', 'Domestic Publications']]) {
  tex += `\\textbf{${label}}\n\\begin{enumerate}\n`;
  for (const pub of publications.filter(p => p.category === category)) {
    tex += `\\item \\begin{minipage}[t]{\\linewidth}${escape(pub.authors).replaceAll('Taegyun Kwon', '\\textbf{Taegyun Kwon}')}.\n`;
    tex += `\`\`${escape(pub.title)}''\\\\\\textit{${escape(pub.venue)}}\n`;
    if (pub.links?.[0]) tex += `\\href{${pub.links[0].url}}{[Paper]}\n`;
    tex += '\\end{minipage}\n';
  }
  tex += '\\end{enumerate}\n';
}
tex += '\\end{rSection}\n';
const target = new URL('../cv/publications.tex', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== tex) throw new Error('CV publications are stale. Run npm run cv:sync.');
} else writeFileSync(target, tex);
